def ensure_reference_data(db: Session) -> None:
    have_templates = {(t.stage, t.title) for t in db.scalars(select(TaskTemplate))}
    for stage, title, offset in TASK_TEMPLATES:
        if (stage, title) not in have_templates:
            db.add(TaskTemplate(stage=stage, title=title, default_offset_days=offset))
    have_tips = {(t.topic, t.title) for t in db.scalars(select(Tip))}
    for topic, title, body in TIPS:
        if (topic, title) not in have_tips:
            db.add(Tip(topic=topic, title=title, body=body))
    # снимок из кода не перетирает цены, обновлённые скриптом позже: записывается, только если он новее
    have_prices = {c.slug: c.checked_on for c in db.scalars(select(CityPrice))}
    for slug, name, movers, trucks in CITY_PRICES:
        if slug in have_prices and have_prices[slug] >= PRICES_CHECKED_ON:
            continue
        db.merge(
            CityPrice(
                slug=slug,
                name=name,
                mover_low=movers[0],
                mover_high=movers[1],
                movers_offers=movers[2],
                truck_low=trucks[0],
                truck_high=trucks[1],
                trucks_offers=trucks[2],
                source=PRICES_SOURCE,
                checked_on=PRICES_CHECKED_ON,
            )
        )
    db.commit()


